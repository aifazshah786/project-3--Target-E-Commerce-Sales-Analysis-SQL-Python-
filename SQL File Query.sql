--Q1.Calculate number of orders per month in 2018.

SELECT 
    YEAR(order_purchase_timestamp) AS Year,
    MONTH(order_purchase_timestamp) AS Month,
    COUNT(order_id) AS Total_Orders

FROM orders$

WHERE order_purchase_timestamp >= '2018-01-01'
AND order_purchase_timestamp < '2019-01-01'

GROUP BY 
    YEAR(order_purchase_timestamp),
    MONTH(order_purchase_timestamp)

ORDER BY Year, Month;


--Q2 Find the average number of products per order,grouped by customer city.

SELECT 
    c.customer_city,
    AVG(Product_Count) AS Avg_Products_Per_Order
FROM
(
    SELECT 
        o.order_id,
        o.customer_id,
        COUNT(oi.product_id) AS Product_Count
    FROM orders$ o
    JOIN order_items$ oi
        ON o.order_id = oi.order_id
    GROUP BY 
        o.order_id,
        o.customer_id
) AS OrderProductCount
JOIN customers$ c
    ON OrderProductCount.customer_id = c.customer_id
GROUP BY c.customer_city
ORDER BY Avg_Products_Per_Order DESC;

--Q3. Calculate the percentage of total revenue contributed by each product category.

SELECT 
    p.[product category],
    
    SUM(oi.price) AS Category_Revenue,

    SUM(oi.price) * 100.0 /
    (SELECT SUM(price) FROM order_items$) 
    AS Revenue_Percentage

FROM order_items$ oi

JOIN products$ p
    ON oi.product_id = p.product_id

GROUP BY p.[product category]

ORDER BY Revenue_Percentage DESC;

