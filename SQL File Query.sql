--1.Calculate the moving average of order values for each customer over their order history

SELECT 
    o.customer_id,
    o.order_purchase_timestamp,
    SUM(p.payment_value) AS Order_Value,

    AVG(SUM(p.payment_value)) OVER
    (
        PARTITION BY o.customer_id
        ORDER BY o.order_purchase_timestamp
    ) AS Moving_Average

FROM dbo.orders$ o

JOIN dbo.payments$ p
ON o.order_id = p.order_id

GROUP BY 
    o.customer_id,
    o.order_purchase_timestamp

ORDER BY 
    o.customer_id,
    o.order_purchase_timestamp;

--Q2.Calculate the cumulative sales per month for each year

	SELECT 
    YEAR(o.order_purchase_timestamp) AS Year,
    MONTH(o.order_purchase_timestamp) AS Month,

    -- Monthly sales
    SUM(p.payment_value) AS Monthly_Sales,

    -- Cumulative sales
    SUM(SUM(p.payment_value)) OVER
    (
        PARTITION BY YEAR(o.order_purchase_timestamp)
        ORDER BY MONTH(o.order_purchase_timestamp)
    ) AS Cumulative_Sales

FROM dbo.orders$ o

JOIN dbo.payments$ p
ON o.order_id = p.order_id

GROUP BY 
    YEAR(o.order_purchase_timestamp),
    MONTH(o.order_purchase_timestamp)

ORDER BY Year, Month;


--Q3.Calculate the year-over-year growth rate of total sales.

SELECT 
    YEAR(o.order_purchase_timestamp) AS Year,

    SUM(p.payment_value) AS Total_Sales,

    LAG(SUM(p.payment_value)) OVER
    (
        ORDER BY YEAR(o.order_purchase_timestamp)
    ) AS Previous_Year_Sales,

    (
        SUM(p.payment_value)
        - LAG(SUM(p.payment_value)) OVER
        (ORDER BY YEAR(o.order_purchase_timestamp))
    ) * 100.0

    /

    LAG(SUM(p.payment_value)) OVER
    (ORDER BY YEAR(o.order_purchase_timestamp))

    AS YoY_Growth_Percentage

FROM dbo.orders$ o

JOIN dbo.payments$ p
ON o.order_id = p.order_id

GROUP BY YEAR(o.order_purchase_timestamp)

ORDER BY Year;


--Q4.Calculate the retention rate of customers, defined as the percentage of customers who make another purchase within 6 months of their first purchase.

 WITH FirstPurchase AS
(
    SELECT
        customer_id,
        MIN(order_purchase_timestamp) AS first_purchase_date
    FROM dbo.orders$
    GROUP BY customer_id
),

NextPurchase AS
(
    SELECT
        fp.customer_id,
        fp.first_purchase_date,
        MIN(o.order_purchase_timestamp) AS next_purchase_date
    FROM FirstPurchase fp
    JOIN dbo.orders$ o
        ON fp.customer_id = o.customer_id
        AND o.order_purchase_timestamp > fp.first_purchase_date
    GROUP BY
        fp.customer_id,
        fp.first_purchase_date
)

SELECT

COUNT(customer_id) * 100.0 /

(
SELECT COUNT(*) FROM FirstPurchase
)

AS Retention_Rate_Percentage

FROM NextPurchase

WHERE DATEDIFF(MONTH, first_purchase_date, next_purchase_date) <= 6;



--Q5.Identify the top 3 customers who spent the most money in each year.


WITH CustomerYearSales AS
(
    SELECT 
        YEAR(o.order_purchase_timestamp) AS Year,
        o.customer_id,
        SUM(p.payment_value) AS TotalSpent

    FROM dbo.orders$ o

    JOIN dbo.payments$ p
        ON o.order_id = p.order_id

    GROUP BY 
        YEAR(o.order_purchase_timestamp),
        o.customer_id
),

RankedCustomers AS
(
    SELECT *,
    
    RANK() OVER
    (
        PARTITION BY Year
        ORDER BY TotalSpent DESC
    ) AS RankNum

    FROM CustomerYearSales
)

SELECT 
    Year,
    customer_id,
    TotalSpent,
    RankNum

FROM RankedCustomers

WHERE RankNum <= 3

ORDER BY Year, RankNum;

